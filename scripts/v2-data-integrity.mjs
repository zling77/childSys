import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const dir=path.resolve(process.argv[2]??'');if(!process.argv[2])throw new Error('Pass run directory');
const config=JSON.parse(fs.readFileSync(path.join(dir,'config.json'),'utf8'));
const corpus=JSON.parse(fs.readFileSync(config.corpusPath,'utf8'));
const backgrounds=JSON.parse(fs.readFileSync('scripts/fixtures/v2-background-replies.json','utf8'));
const rows=fs.readdirSync(dir).filter(n=>/^trajectory-.*\.json$/.test(n)).map(file=>({file,...JSON.parse(fs.readFileSync(path.join(dir,file),'utf8'))}));
const errors=[];const keys=new Set();
for(const r of rows){
  const key=[r.caseId,r.arm,r.repeat].join(':');if(keys.has(key))errors.push({key,error:'duplicate completed trajectory'});keys.add(key);
  const c=corpus.cases.find(c=>c.case_id===r.caseId);
  if(!c){errors.push({key,error:'unknown case'});continue;}
  if(r.turns[0].answer!==c.turns[0].answer||r.turns[0].question!==c.turns[0].question)errors.push({key,error:'opening differs from fixed corpus'});
  if(r.totalTurns!==r.turns.length||r.systemTimeMs!==r.turns.reduce((n,t)=>n+t.latencyMs,0))errors.push({key,error:'turn/time sum mismatch'});
  const cards=new Map(c.turns.map(t=>[`T${t.turn}`,t.answer]));
  if(c.case_id==='R001')cards.set('T3','这两周'+cards.get('T3'));
  if(c.case_id==='R023')cards.set('T2','晚上睡着以后会再醒来。'+cards.get('T2'));
  for(const [i,text] of (backgrounds[c.case_id]??[]).entries())cards.set(`B${i+1}`,text);
  cards.set('UNKNOWN','这个我不知道。');cards.set('CONTROL_RETRY','我准备好了，可以继续。');
  for(let i=1;i<r.turns.length;i++){
    const t=r.turns[i],prior=r.turns[i-1];
    if(t.question!==prior.nextQuestion?.text)errors.push({key,turn:t.turn,error:'question was not generated by tested arm'});
    if(t.answer!==cards.get(t.card))errors.push({key,turn:t.turn,error:'answer is not frozen card'});
    if(t.turn!==i+1)errors.push({key,turn:t.turn,error:'unexpected turn index'});
  }
  const badModels=r.modelAudits.filter(a=>a.model!=='qwen3.8:27b'&&!['none','unknown'].includes(a.model));
  if(r.arm==='rule'&&r.modelAudits.length)errors.push({key,error:'rule arm has model audit calls'});
  if(r.arm==='qwen38'&&badModels.length)errors.push({key,error:'wrong target LLM model',models:badModels.map(a=>a.model)});
}
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const changedRuntime=Object.entries(config.protectedHashes).filter(([p,h])=>hash(p)!==h).map(([p])=>p);
let changedBaseline=[];
const baselineMeta=path.join(dir,'service-and-baseline-metadata.json');
if(fs.existsSync(baselineMeta))changedBaseline=Object.entries(JSON.parse(fs.readFileSync(baselineMeta,'utf8')).baselineRuntimeHashes).filter(([p,h])=>hash(path.join('../ChildPsych-rule-baseline',p))!==h).map(([p])=>p);
const missing=[];
for(const c of corpus.cases)for(const arm of ['rule','qwen38'])for(const repeat of config.repeatedCases.includes(c.case_id)?[1,2,3]:[1]){
  if(!keys.has([c.case_id,arm,repeat].join(':')))missing.push({caseId:c.case_id,arm,repeat});
}
const result={checkedAt:new Date().toISOString(),completedTrajectories:rows.length,expected:84,missing,errors,changedRuntime,changedBaseline,
  allCompletedDataValid:!errors.length&&!changedRuntime.length&&!changedBaseline.length,experimentComplete:!missing.length};
if(process.env.V2_INTEGRITY_SAVE)fs.writeFileSync(path.join(dir,'data-integrity.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
if(errors.length||changedRuntime.length||changedBaseline.length)process.exitCode=1;
